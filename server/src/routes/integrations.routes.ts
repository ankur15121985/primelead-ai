router.get(
  '/',
  asyncHandler(async (req, res) => {
    const user = (req as AuthedRequest).user;
    const rows = await prisma.integration.findMany({ where: { orgId: user.orgId }, orderBy: { source: 'asc' } });
    const connections = rows.map((r) => ({
      id: r.id,
      source: r.source,
      name: r.name,
      enabled: r.enabled,
      status: r.status,
      webhookUrl: r.webhookUrl,
      hasWebhookSecret: Boolean(r.webhookSecret),
      lastSyncAt: r.lastSyncAt,
      errorCount: r.errorCount,
      lastError: r.lastError,
      config: r.config ? Object.fromEntries(Object.entries(r.config as Record<string, unknown>).filter(([k]) => !/key|secret|token|password/i.test(k))) : {},
      createdAt: r.createdAt,
    }));
    const catalog = INTEGRATION_CATALOG.map((c) => ({
      ...c,
      connected: rows.some((r) => r.source === c.source),
    }));
    return ok(res, { catalog, connections });
  })
);

/** Generate (or regenerate) a webhook secret + URL for a source. */
router.post(
  '/:source/connect',
  requirePermission('integrations.manage'),
  asyncHandler(async (req, res) => {
    const user = (req as AuthedRequest).user;
    assertManagerOrAbove(user);
    const source = String(req.params.source).toUpperCase();
    const entry = INTEGRATION_CATALOG.find((c) => c.source === source);
    if (!entry) throw badRequest('Unknown integration source.');

    const secret = crypto.randomBytes(24).toString('hex');
    const webhookUrl = `${config.appUrl}/api/webhooks/${source.toLowerCase()}`;
    const existing = await prisma.integration.findFirst({ where: { orgId: user.orgId, source } });
    const integration = existing
      ? await prisma.integration.update({
          where: { id: existing.id },
          data: { webhookSecret: secret, webhookUrl, name: entry.name, enabled: true, status: 'CONNECTED' },
        })
      : await prisma.integration.create({
          data: { orgId: user.orgId, source, name: entry.name, webhookSecret: secret, webhookUrl, enabled: true, status: 'CONNECTED' },
        });

    await audit({
      orgId: user.orgId,
      userId: user.id,
      action: existing ? 'INTEGRATION_SECRET_REFRESHED' : 'INTEGRATION_CONNECTED',
      entity: 'Integration',
      entityId: integration.id,
      metadata: { source },
      req,
    });
    return ok(res, {
      integration: {
        id: integration.id,
        source,
        name: entry.name,
        webhookUrl,
        webhookSecret: secret, // shown exactly once, right here
      },
    });
  })
);

router.patch(
  '/:source',
  requirePermission('integrations.manage'),
  asyncHandler(async (req, res) => {
    const user = (req as AuthedRequest).user;
    assertManagerOrAbove(user);
    const source = String(req.params.source).toUpperCase();
    const input = validate(integrationUpdateSchema, req.body);
    const existing = await prisma.integration.findFirst({ where: { orgId: user.orgId, source } });
    if (!existing) throw badRequest('Connect this integration first.');

    const updated = await prisma.integration.update({
      where: { id: existing.id },
      data: {
        name: input.name ?? undefined,
        enabled: input.enabled ?? undefined,
        status: input.status ?? undefined,
        config: input.config ? (input.config as any) : undefined,
        ...(input.enabled && input.enabled !== existing.enabled ? { lastSyncAt: new Date() } : {}),
      },
    });
    await audit({ orgId: user.orgId, userId: user.id, action: 'INTEGRATION_UPDATED', entity: 'Integration', entityId: existing.id, metadata: { source }, req });
    return ok(res, { updated: true, status: updated.status, enabled: updated.enabled });
  })
);

router.delete(
  '/:source',
  requirePermission('integrations.manage'),
  asyncHandler(async (req, res) => {
    const user = (req as AuthedRequest).user;
    assertManagerOrAbove(user);
    const source = String(req.params.source).toUpperCase();
    const existing = await prisma.integration.findFirst({ where: { orgId: user.orgId, source } });
    if (!existing) throw badRequest('Not connected.');
    await prisma.integration.delete({ where: { id: existing.id } });
    await audit({ orgId: user.orgId, userId: user.id, action: 'INTEGRATION_DISCONNECTED', entity: 'Integration', entityId: existing.id, metadata: { source }, req });
    return ok(res, { deleted: true });
  })
);

/** Recent ingestion activity for a source — the connection's audit trail. */
router.get(
  '/:source/logs',
  requirePermission('integrations.manage'),
  asyncHandler(async (req, res) => {
    const user = (req as AuthedRequest).user;
    const source = String(req.params.source).toUpperCase();
    const existing = await prisma.integration.findFirst({ where: { orgId: user.orgId, source } });
    if (!existing) throw badRequest('Connect this integration first.');
    const status = String(req.query.status || '').toUpperCase();
    const logs = await prisma.integrationLog.findMany({
      where: { orgId: user.orgId, source, ...(status ? { status } : {}) },
      orderBy: { createdAt: 'desc' },
      take: 50,
      include: { integration: { select: { id: true, source: true, status: true, lastSyncAt: true, errorCount: true, lastError: true } } },
    });
    const health = logs[0]?.integration || null;
    return ok(res, {
      logs: logs.map((l) => ({
        id: l.id,
        status: l.status,
        message: l.message,
        error: l.error,
        leadId: l.leadId,
        externalId: l.externalId,
        createdAt: l.createdAt,
      })),
      health: health
        ? { status: health.status, lastSyncAt: health.lastSyncAt, errorCount: health.errorCount, lastError: health.lastError }
        : null,
      counts: {
        success: await prisma.integrationLog.count({ where: { orgId: user.orgId, source, status: 'SUCCESS' } }),
        duplicate: await prisma.integrationLog.count({ where: { orgId: user.orgId, source, status: 'DUPLICATE' } }),
        invalid: await prisma.integrationLog.count({ where: { orgId: user.orgId, source, status: 'INVALID' } }),
        failed: await prisma.integrationLog.count({ where: { orgId: user.orgId, source, status: 'FAILED' } }),
      },
    });
  })
);

export default router;
