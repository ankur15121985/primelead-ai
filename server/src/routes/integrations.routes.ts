/**
 * Integrations & lead-source connections.
 *
 * Architecture: an org can connect a lead source (WhatsApp, Facebook,
 * IndiaMART, Shopify, webhook, API…) by generating a unique webhook secret +
 * URL, or by saving provider config (kept server-side only). This module never
 * pretends a connection works without credentials — every "connect" action is
 * explicit and reversible.
 *
 *  - GET    /           catalog + the org's current connections
 *  - POST   /:source/connect    create/refresh a webhook secret (manager+)
 *  - PATCH  /:source   update config / enabled / status
 *  - DELETE /:source   disconnect (manager+)
 */
